<?php

declare(strict_types=1);

namespace ImperaTagadaProHeadless\Core\RestApi\Contract;


use Respect\Validation\Validator as v;
use Respect\Validation\Exceptions\NestedValidationException;
use WP_REST_Request;
use WP_REST_Response;
use BadMethodCallException;

/**
 * Abstract Class AbstractValidatorMiddleware
 *
 * Provides a reusable, declarative engine for request validation using Respect/Validation.
 */
abstract class AbstractValidatorMiddleware
{
    /**
     * Define the validation rules mapping parameter keys to Respect\Validation chains.
     *
     * @return array<string, \Respect\Validation\Validatable>
     */
    abstract protected function getRules(WP_REST_Request $request): array;

    /**
     * Core middleware execution logic invoked by the Action pipeline.
     */
    public function __invoke(WP_REST_Request $request, callable $next): mixed
    {
        $rules = $this->getRules($request);
        $errors = [];

        foreach ($rules as $field => $validator) {
            // We fetch the parameter directly from the request context
            $value = $request->get_param($field);

            try {
                // Assert throws an exception if any rule in the chain fails
                $validator->assert($value);
            } catch (NestedValidationException $e) {
                // Extract human-readable error messages generated by Respect
                $errors[$field] = $e->getMessages();
            }
        }

        // If any validation constraints are violated, short-circuit the pipeline immediately
        if (!empty($errors)) {
            return new WP_REST_Response([
                'success' => false,
                'error'   => 'VALIDATION_FAILED',
                'message' => 'The provided request payload contains invalid parameters.',
                'details' => $errors
            ], 400);
        }

        // Constraints passed successfully, advance to the next middleware or controller layer
        return $next($request);
    }

    /**
     * Proxies static magic calls directly to the Respect\Validation engine.
     * This eliminates the need for child classes to import the Respect Validator facade.
     *
     * @param string $name Validation rule name (e.g., 'intVal', 'domain').
     * @param array $arguments Arguments passed to the rule context.
     * @return mixed A validatable constraint chain component.
     * @throws BadMethodCallException If the requested validation rule does not exist.
     */
    public static function __callStatic(string $name, array $arguments): mixed
    {

        try {
            return v::$name(...$arguments);
        } catch (\Throwable $e) {
            throw new BadMethodCallException(
                sprintf('Validation rule initialization error "%s": %s', $name, $e->getMessage()),
                0,
                $e
            );
        }
    }
}
